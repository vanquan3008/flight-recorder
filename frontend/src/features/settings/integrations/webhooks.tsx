import { CreateForm, FormError } from "../form-parts";
import { secondaryButtonClass } from "../../../shared/ui/styles";
import { useMutation, useQueryClient } from "@tanstack/react-query";
import { type FormEvent, useState } from "react";
import { useAuth } from "../../../shared/session";
import { api, APIError, pageItems, usePagedQuery } from "../../../shared/api";
import { Badge, Empty, PagedTable, Panel, formatTime } from "../../../shared/ui";
import { SecretNotice } from "../secret-notice";
import type { Webhook, WebhookDelivery } from "./types";

type Actions = { webhook: Webhook; selected: boolean; busy: boolean; onSelect: (id: string) => void; onToggle: () => void; onRotate: () => void; onDelete: () => void };

export function WebhooksSection() {
  const { credential } = useAuth();
  const queryClient = useQueryClient();
  const [secret, setSecret] = useState<{ title: string; secret: string } | null>(null);
  const [selected, setSelected] = useState("");
  const query = usePagedQuery<Webhook>(["settings-webhooks"], "/api/v1/webhooks?limit=50", credential);
  const hooks = pageItems(query.data?.pages);
  const refresh = () => queryClient.invalidateQueries({ queryKey: ["settings-webhooks"] });
  const create = useMutation({
    mutationFn: (body: { name: string; url: string; events: string[] }) => api<{ webhook: Webhook; secret: string }>("/api/v1/webhooks", credential, { method: "POST", body: JSON.stringify(body) }),
    onSuccess: async (result) => { setSecret({ title: `Signing secret for “${result.webhook.name}”`, secret: result.secret }); await refresh(); },
  });
  const rotate = useMutation({
    mutationFn: (hook: Webhook) => api<{ secret: string }>(`/api/v1/webhooks/${hook.id}/rotate`, credential, { method: "POST" }).then((result) => ({ hook, result })),
    onSuccess: ({ hook, result }) => setSecret({ title: `New signing secret for “${hook.name}”`, secret: result.secret }),
  });
  const toggle = useMutation({
    mutationFn: (hook: Webhook) => api<Webhook>(`/api/v1/webhooks/${hook.id}`, credential, { method: "PUT", body: JSON.stringify({ name: hook.name, url: hook.url, events: hook.events, enabled: !hook.enabled }) }),
    onSuccess: refresh,
  });
  const remove = useMutation({
    mutationFn: (hook: Webhook) => api<void>(`/api/v1/webhooks/${hook.id}`, credential, { method: "DELETE" }),
    onSuccess: async () => { setSelected(""); await refresh(); },
  });
  if (query.error instanceof APIError && query.error.status === 501) {
    return <Panel title="Webhooks"><Empty>Webhook notifications are not enabled on this server. Enable them in the deployment configuration to manage endpoints here.</Empty></Panel>;
  }
  const submit = (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    const form = event.currentTarget;
    const values = new FormData(form);
    create.mutate({ name: String(values.get("name") || "").trim(), url: String(values.get("url") || "").trim(), events: ["incident.opened"] }, { onSuccess: () => form.reset() });
  };
  const failure = create.error || rotate.error || toggle.error || remove.error;
  const busy = toggle.isPending || rotate.isPending || remove.isPending;
  const chosen = hooks.find((hook) => hook.id === selected);
  return <>
    {secret && <SecretNotice {...secret} onDismiss={() => setSecret(null)} />}
    <Panel title="Webhook endpoints" meta={`${hooks.length} loaded`}>
      <CreateForm title="New webhook" hint={<>Sends <code>incident.opened</code> events, signed with a secret generated by the server.</>} onSubmit={submit}
        submit={{ pending: create.isPending, label: "Add webhook", pendingLabel: "Creating…" }}>
        <label>Name<input name="name" required maxLength={128} placeholder="e.g. on-call chat" /></label>
        <label>HTTPS endpoint<input name="url" type="url" required pattern="https://.*" placeholder="https://hooks.example.com/tracepilot" /></label>
      </CreateForm>
      <FormError error={failure} />
      <PagedTable query={query} empty="No webhooks configured." headers={["Name", "Endpoint", "Events", "Status", "Actions"]}
        rows={hooks.map((hook) => [hook.name, <code>{hook.url}</code>, hook.events.join(", "), <Badge value={hook.enabled ? "ACTIVE" : "DISABLED"} />,
          <HookActions webhook={hook} selected={selected === hook.id} busy={busy} onSelect={setSelected} onToggle={() => toggle.mutate(hook)} onRotate={() => rotate.mutate(hook)} onDelete={() => remove.mutate(hook)} />])} />
    </Panel>
    {chosen && <Deliveries webhook={chosen} />}
  </>;
}

function HookActions({ webhook, selected, busy, onSelect, onToggle, onRotate, onDelete }: Actions) {
  const [confirming, setConfirming] = useState(false);
  if (confirming) return <span className="inline-confirm inline-flex flex-wrap items-center gap-1.5"><button className="button-danger inline-flex items-center justify-center gap-1.5 whitespace-nowrap rounded-lg border px-3 py-1.5 text-xs font-semibold leading-snug transition-colors hover:border-accent/45 border-danger/40 bg-danger-bg text-danger-fg hover:bg-danger/20" onClick={onDelete}>Confirm delete</button><button className={`button-secondary ${secondaryButtonClass}`} onClick={() => setConfirming(false)}>Cancel</button></span>;
  return <span className="table-actions inline-flex flex-wrap items-center gap-1.5">
    <button className={`button-secondary ${secondaryButtonClass}`} aria-pressed={selected} onClick={() => onSelect(selected ? "" : webhook.id)}>{selected ? "Hide deliveries" : "Deliveries"}</button>
    <button className={`button-secondary ${secondaryButtonClass}`} disabled={busy} onClick={onToggle}>{webhook.enabled ? "Disable" : "Enable"}</button>
    <button className={`button-secondary ${secondaryButtonClass}`} disabled={busy} onClick={onRotate} aria-label={`Rotate secret for ${webhook.name}`}>Rotate secret</button>
    <button className="button-danger inline-flex items-center justify-center gap-1.5 whitespace-nowrap rounded-lg border px-3 py-1.5 text-xs font-semibold leading-snug transition-colors hover:border-accent/45 border-danger/40 bg-danger-bg text-danger-fg hover:bg-danger/20" onClick={() => setConfirming(true)} aria-label={`Delete ${webhook.name}`}>Delete</button>
  </span>;
}

function Deliveries({ webhook }: { webhook: Webhook }) {
  const { credential } = useAuth();
  const query = usePagedQuery<WebhookDelivery>(["settings-deliveries", webhook.id], `/api/v1/webhooks/${webhook.id}/deliveries?limit=50`, credential);
  const rows = pageItems(query.data?.pages);
  return <Panel title={`Delivery history · ${webhook.name}`} meta={`${rows.length} loaded`}>
    <PagedTable query={query} empty="No deliveries yet. An attempt is recorded each time an incident opens." headers={["Created", "Event", "Status", "Attempt", "HTTP", "Next attempt", "Last error"]}
      rows={rows.map((row) => [formatTime(row.created_at), row.event_type, <Badge value={row.status} />, `${row.attempt}/${row.max_attempts}`, row.http_status ?? "—", formatTime(row.next_attempt_at), row.last_error || "—"])} />
  </Panel>;
}
