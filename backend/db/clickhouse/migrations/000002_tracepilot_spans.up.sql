CREATE TABLE IF NOT EXISTS tracepilot_spans (
    project_id UUID,
    environment_id UUID,
    event_id UUID,
    trace_id String CODEC(ZSTD(1)),
    span_id String CODEC(ZSTD(1)),
    parent_span_id String CODEC(ZSTD(1)),
    trace_state String CODEC(ZSTD(1)),
    span_name LowCardinality(String),
    span_kind Int32,
    started_at DateTime64(9, 'UTC') CODEC(Delta, ZSTD(1)),
    ended_at DateTime64(9, 'UTC') CODEC(Delta, ZSTD(1)),
    duration_ns Int64 CODEC(T64, ZSTD(1)),
    status_code LowCardinality(String),
    status_message String CODEC(ZSTD(1)),
    flags UInt32,
    service_name LowCardinality(String),
    service_version LowCardinality(String),
    resource_schema_url LowCardinality(String),
    resource_attributes Map(LowCardinality(String), String) CODEC(ZSTD(1)),
    scope_name LowCardinality(String),
    scope_version LowCardinality(String),
    scope_schema_url LowCardinality(String),
    scope_attributes Map(LowCardinality(String), String) CODEC(ZSTD(1)),
    span_attributes Map(LowCardinality(String), String) CODEC(ZSTD(1)),
    span_events String CODEC(ZSTD(1)),
    span_links String CODEC(ZSTD(1)),
    dropped_attributes_count UInt32,
    dropped_events_count UInt32,
    dropped_links_count UInt32,
    endpoint String CODEC(ZSTD(1)),
    request_failed Bool,
    dependency_type LowCardinality(String),
    dependency_name String CODEC(ZSTD(1)),
    INDEX trace_lookup trace_id TYPE bloom_filter(0.001) GRANULARITY 1,
    INDEX resource_keys mapKeys(resource_attributes) TYPE bloom_filter(0.01) GRANULARITY 1,
    INDEX resource_values mapValues(resource_attributes) TYPE bloom_filter(0.01) GRANULARITY 1,
    INDEX attribute_keys mapKeys(span_attributes) TYPE bloom_filter(0.01) GRANULARITY 1,
    INDEX attribute_values mapValues(span_attributes) TYPE bloom_filter(0.01) GRANULARITY 1,
    INDEX duration_range duration_ns TYPE minmax GRANULARITY 1
)
ENGINE = ReplacingMergeTree
PARTITION BY toStartOfWeek(started_at, 1, 'UTC')
ORDER BY (project_id, environment_id, service_name, started_at, event_id)
